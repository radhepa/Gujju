import { writeFileSync } from 'fs';
import { CHECKS, EXCEPTIONS, runCheck } from '../content/accuracy';

// The 100 accuracy checks (see src/content/accuracy.ts). Run with
// ACCURACY_REPORT=1 to also write docs/accuracy.md.
describe('accuracy', () => {
  it('has exactly 100 checks, numbered 1 to 100', () => {
    expect(CHECKS.map((c) => c.id)).toEqual(Array.from({ length: 100 }, (_, i) => i + 1));
  });

  it('every exception still matches a real violation', () => {
    const stale: string[] = [];
    for (const c of CHECKS) {
      const all = new Set(c.run());
      for (const key of Object.keys(EXCEPTIONS[c.id] ?? {})) if (!all.has(key)) stale.push(`${c.id}: ${key}`);
    }
    expect(stale).toEqual([]);
  });

  for (const c of CHECKS) {
    it(`${String(c.id).padStart(3, '0')} ${c.name}`, () => {
      expect(runCheck(c).violations).toEqual([]);
    });
  }

  afterAll(() => {
    if (!process.env.ACCURACY_REPORT) return;
    const rows = CHECKS.map((c) => {
      const r = runCheck(c);
      return `| ${c.id} | ${c.name} | ${r.violations.length ? `❌ ${r.violations.length}` : '✅'} | ${r.excused || ''} |`;
    });
    writeFileSync(
      'docs/accuracy.md',
      ['# Content accuracy checks', '', 'Generated by `ACCURACY_REPORT=1 npx jest accuracy`. Exceptions are violations a person checked and accepted; the reasons are in `src/content/accuracy.ts`.', '', '| # | Check | Result | Reviewed exceptions |', '|---|---|---|---|', ...rows, ''].join('\n'),
    );
  });
});
