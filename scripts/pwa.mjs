// Runs after `expo export -p web`. Turns dist/ into an installable app that
// works offline: a manifest, home-screen icons, and a service worker that
// keeps a copy of the app on the phone. Nothing here touches progress, which
// lives in the browser's IndexedDB and never leaves the device.
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const DIST = 'dist';

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const p = join(dir, name);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(DIST).map((p) => '/' + relative(DIST, p).split(sep).join('/'));

// The app bundle, its images, the fonts it actually loads and the icons.
// Expo copies every icon font in @expo/vector-icons; only Ionicons is used,
// so the other few megabytes are left to load on demand if ever needed.
const FONTS = /(Nunito_(400Regular|700Bold|800ExtraBold)|NotoSansGujarati_(400Regular|700Bold)|Ionicons)\.[0-9a-f]+\.ttf$/;
const precache = [
  '/',
  ...files.filter(
    (f) =>
      f.startsWith('/_expo/') ||
      f.startsWith('/assets/assets/') ||
      f.startsWith('/icons/') ||
      f === '/favicon.ico' ||
      FONTS.test(f),
  ),
  '/manifest.webmanifest',
].filter((f) => f !== '/index.html');

const version = createHash('sha256')
  .update(readFileSync(join(DIST, 'index.html')))
  .update(precache.join('\n'))
  .digest('hex')
  .slice(0, 12);

const manifest = {
  id: '/',
  name: 'Gujju: learn Gujarati',
  short_name: 'Gujju',
  description: 'Learn to read and write Gujarati, with Kesar the lion.',
  start_url: '/',
  scope: '/',
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#FBF6EE',
  theme_color: '#E58E26',
  icons: [
    { src: '/icons/icon-192.png', sizes: '192x192', type: 'image/png', purpose: 'any' },
    { src: '/icons/icon-512.png', sizes: '512x512', type: 'image/png', purpose: 'any' },
    { src: '/icons/maskable-512.png', sizes: '512x512', type: 'image/png', purpose: 'maskable' },
  ],
};
writeFileSync(join(DIST, 'manifest.webmanifest'), JSON.stringify(manifest, null, 2));

const sw = `// Generated by scripts/pwa.mjs. Keeps Gujju working with no signal.
const CACHE = 'gujju-${version}';
const PRECACHE = ${JSON.stringify(precache)};

self.addEventListener('install', (e) => {
  e.waitUntil(caches.open(CACHE).then((c) => c.addAll(PRECACHE)).then(() => self.skipWaiting()));
});

self.addEventListener('activate', (e) => {
  e.waitUntil(
    caches
      .keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith('gujju-') && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim()),
  );
});

// Pages: try the network for a fresh version, but don't keep the learner
// waiting on a bad signal. Everything else has a hashed name, so the cached
// copy is always right.
self.addEventListener('fetch', (e) => {
  const req = e.request;
  if (req.method !== 'GET') return;
  const url = new URL(req.url);
  if (url.origin !== self.location.origin) return;

  if (req.mode === 'navigate') {
    e.respondWith(
      (async () => {
        const cache = await caches.open(CACHE);
        const net = fetch(req).then((res) => {
          if (res.ok) cache.put('/', res.clone());
          return res;
        });
        const slow = new Promise((resolve) => setTimeout(resolve, 3000));
        const res = await Promise.race([net.catch(() => null), slow]);
        return res || (await cache.match('/')) || net;
      })(),
    );
    return;
  }

  e.respondWith(
    caches.match(req).then(
      (hit) =>
        hit ||
        fetch(req).then((res) => {
          if (res.ok) {
            const copy = res.clone();
            caches.open(CACHE).then((c) => c.put(req, copy));
          }
          return res;
        }),
    ),
  );
});
`;
writeFileSync(join(DIST, 'sw.js'), sw);

writeFileSync(
  join(DIST, 'register-sw.js'),
  "if ('serviceWorker' in navigator) {\n  window.addEventListener('load', () => navigator.serviceWorker.register('/sw.js').catch(() => {}));\n}\n",
);

const head = [
  '<meta name="description" content="Learn to read and write Gujarati, with Kesar the lion.">',
  '<meta name="referrer" content="no-referrer">',
  '<link rel="manifest" href="/manifest.webmanifest">',
  '<link rel="apple-touch-icon" href="/icons/apple-touch-icon.png">',
  '<meta name="apple-mobile-web-app-capable" content="yes">',
  '<meta name="mobile-web-app-capable" content="yes">',
  '<meta name="apple-mobile-web-app-title" content="Gujju">',
  '<meta name="apple-mobile-web-app-status-bar-style" content="default">',
  '<script src="/register-sw.js" defer></script>',
].join('\n');

const indexPath = join(DIST, 'index.html');
const html = readFileSync(indexPath, 'utf8');
if (!html.includes('rel="manifest"')) writeFileSync(indexPath, html.replace('</head>', `${head}\n</head>`));

const kb = precache.reduce((n, f) => n + (f === '/' ? 0 : statSync(join(DIST, f)).size), 0) / 1024;
console.log(`pwa: ${precache.length} files (${Math.round(kb)} KB) cached for offline, version ${version}`);
